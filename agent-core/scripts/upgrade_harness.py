#!/usr/bin/env python3
"""Upgrade an installed V4 harness from a newer template without losing project changes.

Per harness-owned file (see harness_files.OWNED_PATHS):
  ADD       missing in the project              -> copied
  SAME      already identical to the template   -> nothing to do
  UPDATE    unchanged since the last install    -> replaced (needs the project's HARNESS-MANIFEST.json)
  KEEP      changed by the project, template unchanged since the last install -> kept as is
  CONFLICT  changed by both                     -> kept; the template version is written next to it as <file>.v4-new
  REMOVE    dropped by the template and unchanged in the project -> moved to the backup

Without a manifest (installs made before 4.1.0) every differing file is a CONFLICT unless
--take-template is given for it. Dry run by default; --apply writes, backs up every touched
file to .agent-state/upgrade-backup/<timestamp>/, refreshes the manifest and re-syncs mirrors.
PROJECT.md, the project profile and accepted growth history are never touched.

  python3 agent-core/scripts/upgrade_harness.py --write-manifest            # in the template, before release
  python3 agent-core/scripts/upgrade_harness.py --from /path/to/new-template  # in a project: dry run
  python3 agent-core/scripts/upgrade_harness.py --from /path/to/new-template --apply
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from harness_files import owned_files, sha256  # noqa: E402

MANIFEST = 'agent-core/HARNESS-MANIFEST.json'
GENERATED = ('.agents/AGENTS.md', '.claude/skills/')  # mirrors regenerated by sync_agent_config.py


def upgradable(root: Path) -> list[str]:
    return [rel for rel in owned_files(root) if not rel.startswith(GENERATED)]


def build_manifest(root: Path) -> dict:
    version = (root / 'agent-core/VERSION').read_text().strip() if (root / 'agent-core/VERSION').exists() else 'unknown'
    return {'version': version, 'files': {rel: sha256(root / rel) for rel in upgradable(root)}}


def read_manifest(root: Path) -> dict | None:
    try:
        return json.loads((root / MANIFEST).read_text(encoding='utf-8'))
    except Exception:
        return None


def plan(template: Path, target: Path, take_template: set[str]) -> list[tuple[str, str]]:
    new = build_manifest(template)['files']
    base = (read_manifest(target) or {}).get('files', {})
    actions = []
    for rel, new_hash in sorted(new.items()):
        path = target / rel
        if not path.exists():
            actions.append(('ADD', rel))
            continue
        current = sha256(path)
        if current == new_hash:
            actions.append(('SAME', rel))
        elif base.get(rel) == current or rel in take_template:
            actions.append(('UPDATE', rel))
        elif base.get(rel) == new_hash:
            actions.append(('KEEP', rel))
        else:
            actions.append(('CONFLICT', rel))
    for rel, old_hash in sorted(base.items()):
        if rel not in new and (target / rel).exists() and sha256(target / rel) == old_hash:
            actions.append(('REMOVE', rel))
    return actions


def apply(template: Path, target: Path, actions: list[tuple[str, str]]) -> Path:
    backup = target / '.agent-state/upgrade-backup' / time.strftime('%Y%m%d-%H%M%S')
    for action, rel in actions:
        src, dst = template / rel, target / rel
        if action in ('UPDATE', 'REMOVE') and dst.exists():
            (backup / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(dst, backup / rel)
        if action in ('ADD', 'UPDATE'):
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        elif action == 'CONFLICT':
            shutil.copy2(src, dst.with_name(dst.name + '.v4-new'))
        elif action == 'REMOVE':
            dst.unlink()
    sync = target / 'agent-core/scripts/sync_agent_config.py'
    if sync.exists():
        subprocess.run([sys.executable, '-B', str(sync)], cwd=target, check=False, capture_output=True)
    # The baseline is the template that was offered. Untouched files then upgrade cleanly next
    # time, project-only edits are KEEP, and edits on both sides are CONFLICT again.
    manifest = build_manifest(template)
    (target / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    return backup


def main() -> int:
    ap = argparse.ArgumentParser(description='Safely upgrade harness-owned files from a newer V4 template.')
    ap.add_argument('--from', dest='template', help='path to the new template / extracted package root')
    ap.add_argument('--target', default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--take-template', action='append', default=[], help='treat this conflicting file as UPDATE (repeatable)')
    ap.add_argument('--write-manifest', action='store_true', help='write HARNESS-MANIFEST.json for --target and exit')
    args = ap.parse_args()
    target = Path(args.target).resolve()

    if args.write_manifest:
        data = build_manifest(target)
        (target / MANIFEST).write_text(json.dumps(data, indent=2, sort_keys=True) + '\n', encoding='utf-8')
        print(f"Wrote {MANIFEST} ({len(data['files'])} files, version {data['version']}).")
        return 0
    if not args.template:
        ap.error('--from is required unless --write-manifest')
    template = Path(args.template).resolve()
    if not (template / 'agent-core/hooks/policy.py').exists():
        raise SystemExit(f'Not a V4 template: {template}')
    if template == target:
        raise SystemExit('Template and target are the same directory.')

    actions = plan(template, target, set(args.take_template))
    old = (read_manifest(target) or {}).get('version', 'no manifest')
    new = build_manifest(template)['version']
    print(f'Harness upgrade {old} -> {new} ({"APPLY" if args.apply else "dry run"})')
    for action, rel in actions:
        if action not in ('SAME',):
            print(f'  {action:8} {rel}')
    counts = {a: sum(1 for x, _ in actions if x == a) for a in ('ADD', 'UPDATE', 'KEEP', 'CONFLICT', 'REMOVE', 'SAME')}
    print('  ' + ', '.join(f'{k} {v}' for k, v in counts.items()))
    if args.apply:
        backup = apply(template, target, actions)
        print(f'Applied. Backup of replaced/removed files: {backup}')
        if counts['CONFLICT']:
            print('Resolve each CONFLICT by merging <file>.v4-new into <file>, delete the .v4-new file, then rerun check_agent_config.py.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
